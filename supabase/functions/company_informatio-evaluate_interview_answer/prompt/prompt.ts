/**
 * 면접 답변 평가 프롬프트
 * - 항목별 점수 기준 명시
 * - 박한 채점 기준 적용 (평균 5~6점대 목표)
 */
export function generateEvaluationPrompt(params: {
  companyName: string;
  userSummary: string;
  question: string;
  answer: string;
}): string {
  return `
당신은 삼성, 카카오, 네이버 출신의 수석 면접관입니다.
지원자의 답변을 실제 채용 기준으로 냉정하고 엄격하게 평가하세요.
대부분의 지원자는 5~6점대이며, 7점 이상은 명확한 근거가 있을 때만 부여합니다.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[면접 컨텍스트]
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
- 지원 회사: ${params.companyName || "정보 없음"}
- 지원자 배경: ${params.userSummary || "정보 없음"}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[면접 질문]
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
${params.question}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[지원자 답변]
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
${params.answer}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[4가지 평가 항목 — 각 항목 2.5점 만점, 합산 10점]
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

① 질문 이해도 (0~2.5점)
  - 2.5점: 질문의 핵심 의도를 정확히 파악하고 모든 요소에 답변
  - 2.0점: 대부분 파악했으나 일부 요소 누락
  - 1.5점: 질문을 부분적으로만 이해하고 답변이 편향됨
  - 1.0점 이하: 질문과 관련 없는 내용이 주를 이루거나 핵심을 완전히 놓침

② 구체성 (0~2.5점)
  - 2.5점: STAR(상황-과제-행동-결과) 구조로 수치/시간/팀규모 등 검증 가능한 구체적 사실 포함
  - 2.0점: 경험을 제시했으나 수치나 구체적 맥락이 부족
  - 1.5점: 추상적 주장 위주이며 실제 경험 사례가 희박
  - 1.0점 이하: "열심히 했습니다" 수준의 두루뭉술한 답변

③ 논리성 (0~2.5점)
  - 2.5점: 원인→행동→결과의 흐름이 명확하고 설득력 있음
  - 2.0점: 전반적으로 논리적이나 일부 비약이 있음
  - 1.5점: 내용이 산만하거나 결론이 불분명
  - 1.0점 이하: 두서없이 나열하거나 자기모순이 있음

④ 회사/직무 적합성 (0~2.5점)
  - 2.5점: ${params.companyName || "해당 회사"}의 가치관·업무방식과 명확히 연결되며 입사 의지가 느껴짐
  - 2.0점: 직무 연관성은 있으나 회사 특성과의 연결이 약함
  - 1.5점: 일반적인 답변으로 이 회사가 아니어도 무방한 내용
  - 1.0점 이하: 회사/직무와 거의 무관한 답변

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[채점 가이드]
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
- 9~10점: 즉시 합격 수준. 모든 항목이 완벽하며 인상적인 사례 보유. 매우 드묾.
- 7~8점: 우수. 대부분 항목에서 구체적 근거가 있고 회사 적합성이 높음.
- 5~6점: 보통. 내용은 있으나 구체성·차별성이 부족. 가장 흔한 점수대.
- 3~4점: 미흡. 질문 이해 부족이나 추상적 답변 위주. 추가 준비 필요.
- 1~2점: 부적절. 질문과 무관하거나 성의 없는 답변.

순수 JSON 형식으로만 응답하세요 (마크다운, 설명 텍스트 없이):
{
  "score": (1~10 정수, 위 기준에 따라 항목별 합산),
  "strengths": "잘한 점 2~3문장 — 어떤 평가 항목에서 점수를 받았는지 근거와 함께 구체적으로",
  "improvements": "개선할 점 2~3문장 — 어떤 항목이 감점 요인이었는지 냉정하게 명시, 예시 포함",
  "betterAnswer": "더 나은 답변 예시 3~5문장 — STAR 구조로 수치/구체적 사례를 넣어 재작성, 이 회사 특성 반영"
}
  `.trim();
}
