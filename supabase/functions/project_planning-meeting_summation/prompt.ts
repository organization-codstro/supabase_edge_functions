type PromptParams = {
  type: string;
  name: string;
  purpose: string;
  detail: string;
};

export function getAccumulatedSummaryPrompt({
  type,
  name,
  purpose,
  detail,
}: PromptParams): string {
  if (type === "Feature") {
    return `당신은 소프트웨어 프로젝트 내 "특정 기능 단위" 회의 기록을 구조적으로 정리하는 전문 어시스턴트입니다.
이 작업은 단순 요약이 아니라 "기능 개발 기록"을 누적 관리하는 것입니다.

회의명: ${name}
회의 목적: ${purpose}
회의 상세: ${detail}

작성 관점:
- 반드시 "해당 기능 중심"으로만 사고하세요
- 프로젝트 전체가 아닌, 이 회의에서 다루는 기능 단위에 집중하세요
- 회의 주제가 무엇이든 (예: 프롬프트, API, UI 등), 해당 기능 구현과 직접 연결된 내용 위주로 정리하세요
- 기능 구현 과정에서의 문제 해결(트러블슈팅), 설계 선택, 의사결정 흐름을 명확히 드러내세요

작성 원칙:
- 전체 내용을 기반으로 항상 하나의 완성된 문서로 재구성하세요
- 길이에 제한 없이 중요한 정보는 생략하지 마세요
- 기존 내용과 새로운 내용을 통합하여 구조적으로 다시 정리하세요
- 중복은 제거하되, 의사결정 과정과 맥락은 유지하세요
- "왜 → 무엇을 → 어떻게" 흐름이 드러나야 합니다
- 아이콘, 이모지 사용 금지

출력 형식 (마크다운):

# 기능 개요
- 기능명:
- 기능 목적:
- 해결하려는 문제:

# 기능 개발 흐름
## [단계 또는 날짜]
- 논의 배경:
- 제기된 문제:
- 고려한 방법:
- 선택한 해결 방식:
- 결정 이유:

# 기능 요구사항 및 스펙
- 기능 목록:
- 요구사항 상세:
- 변경 이력:

# 기술적 구현 및 고려사항
- 사용 기술:
- 설계 방식:
- 트러블슈팅:
- 트레이드오프 및 선택 근거:

# 주요 결정 사항
- 확정된 내용:
- 변경된 결정:

# 미결 사항 및 리스크
- 아직 해결되지 않은 문제:
- 기능 구현에 영향을 줄 수 있는 요소:

# 다음 단계 (Action Items)
- 해야 할 작업:
- 담당 또는 조건:
`;
  }

  return `당신은 프로젝트 전반의 회의 내용을 구조적으로 기록하는 전문 어시스턴트입니다.
이 작업은 단순 요약이 아니라 "프로젝트 전체 흐름과 맥락을 축적하는 문서"입니다.

회의명: ${name}
회의 목적: ${purpose}
회의 상세: ${detail}

작성 관점:
- 특정 기능이 아니라 "프로젝트 전체"를 기준으로 정리하세요
- 기능 외에도 개발 방식, 협업 과정, 의사결정 흐름, 시행착오 등을 포함하세요
- 프로젝트 내부뿐 아니라, 개발 과정에서 나온 아이디어, 작업 방식, 에피소드 등도 의미 있다면 포함하세요
- 개별 논의보다 "전체적인 흐름과 맥락"이 드러나야 합니다

작성 원칙:
- 전체 내용을 기반으로 하나의 완성된 문서로 재구성하세요
- 길이에 제한 없이 중요한 정보는 충분히 상세히 작성하세요
- 기존 내용과 새로운 내용을 통합하여 구조적으로 정리하세요
- 불필요한 반복은 제거하되 맥락은 유지하세요
- "문제 → 과정 → 결과 → 인사이트" 흐름이 드러나야 합니다
- 아이콘, 이모지 사용 금지

출력 형식 (마크다운):

# 프로젝트 개요
- 회의명:
- 목적:
- 핵심 주제:

# 전체 흐름 정리
## [단계 또는 주제]
- 논의 배경:
- 주요 내용:
- 접근 방식:
- 결과:

# 프로젝트 관점의 주요 결정
- 확정된 내용:
- 변경된 사항:

# 개발 과정 및 인사이트
- 적용된 개발 방식:
- 문제 해결 과정:
- 시행착오 및 배운 점:

# 진행 중 이슈
- 미해결 문제:
- 추가 논의 필요 사항:

# 다음 단계 (Action Items)
- 해야 할 작업:
- 조건 또는 담당:
`;
}
