/**
 * 면접 질문 생성 프롬프트
 * - 질문을 길고 구체적으로, 회사 맞춤형으로 생성
 * - 과거 답변 질문 목록을 받아 중복 방지
 */
export function buildInterviewQuestionsPrompt(
  companyName: string,
  companyIndustry: string | null,
  companyDescription: string | null,
  companyValues: string | null,
  userSummary: string,
  pastQuestions: string[] = [],
): string {
  const pastQuestionsBlock =
    pastQuestions.length > 0
      ? `
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[이전 면접에서 이미 출제된 질문 — 절대 중복 금지]
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
아래 질문들과 동일하거나 유사한 질문을 생성하면 안 됩니다.
의미, 핵심 키워드, 질문 의도가 겹치는 경우도 중복으로 간주합니다.

${pastQuestions.map((q, i) => `${i + 1}. ${q}`).join("\n")}
`
      : "";

  return `
당신은 삼성, 카카오, 네이버 등 대기업 최종 면접을 수십 차례 진행한 수석 면접관입니다.
지원자의 역량과 회사 적합성을 날카롭게 검증하는 깊이 있는 면접 질문을 생성하세요.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[회사 정보]
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
- 회사명: ${companyName}
- 업종: ${companyIndustry ?? "정보 없음"}
- 회사 소개: ${companyDescription ?? "정보 없음"}
- 핵심 가치: ${companyValues ?? "정보 없음"}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[지원자 프로필]
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
${userSummary}
${pastQuestionsBlock}
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
[질문 생성 필수 규칙]
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

[구성]
- 총 5개 질문
- 인성/가치관 질문 2개: 지원자의 성격, 팀워크, 갈등 해결, 성장 마인드셋 검증
- 직무 역량 질문 2개: 지원자의 실제 기술/경험/문제해결 능력을 구체적으로 검증
- 회사 적합성 질문 1개: ${companyName}의 핵심 가치나 문화에 지원자가 얼마나 부합하는지 검증

[질문 품질 기준]
- 질문 하나당 최소 2~3문장으로 구성 — 상황/배경 설명 + 핵심 질문 + 심화 요청의 구조
- 예시: "개발 일정이 촉박한 상황에서 팀원 간 의견 충돌이 발생한 경험이 있으신가요? 그 상황에서 어떤 방식으로 갈등을 해소하셨는지 구체적인 사례를 들어 설명해주시고, 그 경험에서 본인이 성장한 부분도 함께 말씀해주세요."
- ${companyName}의 업종/핵심 가치/회사 소개를 질문 속에 직접 녹여내야 함
- 지원자 프로필의 구체적인 경험, 기술, 배경을 질문에 반영
- "자기소개 해주세요", "지원 동기는 무엇인가요?" 같은 진부한 질문 절대 금지
- 예/아니오로 답할 수 있는 단순 질문 금지 — 반드시 경험/사고과정/근거를 끌어내는 형태
- 과거 출제 질문과 의미/의도/키워드가 겹치는 질문 생성 금지

순수 JSON 형식으로만 응답하세요 (마크다운, 설명 텍스트 없이):
{
  "questions": [
    {
      "question": "질문 전문 (2~3문장, 구체적 상황 제시 + 핵심 질문 + 심화 요청)",
      "reason": "${companyName}의 [핵심가치/직무/문화]와 지원자의 [구체적 배경]을 연결한 출제 의도 한 줄"
    }
  ]
}
  `.trim();
}
